"""MoQT (Media over QUIC Transport) のプロトコル層。

draft-ietf-moq-transport-21 の codec と sans I/O セッション状態機械を公開する。
この層はストリームの実体に触れない。呼び出し側が peer のストリーム種別を判定して
`Session.receive_*` を呼び、戻り値の `Event` に従ってバイト列を送る。

WebTransport を介した client / server は `moqt.moq` が提供する。
このモジュールは、ワイヤのバイト列を直接組み立てて検証するテストや、実装が送出した
バイト列を検査するテストから使う。

`Event.parameters` と `Message.parameters` はパラメータを「型番号をキーにした
エンコード済みバイト列の辞書」として返す。同じ形式の辞書が `Session.send_*` と
`moqt.moq` の `parameters` 引数に対する入力であり、受信した辞書をそのまま送信経路へ
渡せる。draft が定める値の型と意味で読み書きする場合は `MessageParameters` を使う。
`LocationFilter` は `LOCATION_FILTER` の型付き表現であり、辞書の値としてそのまま
渡せる。

MoQT は draft 由来であり、将来の改訂で変更される可能性がある。
"""

